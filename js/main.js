const languageButtons = document.querySelectorAll('.lang-btn');

function applyTranslations(lang) {
  const selectedLanguage = translations[lang] ? lang : 'pt';
  const selectedTranslations = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage === 'en' ? 'en-US' : selectedLanguage === 'es' ? 'es-ES' : selectedLanguage === 'zh' ? 'zh-CN' : 'pt-BR';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (selectedTranslations[key]) {
      element.textContent = selectedTranslations[key];
    }
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    const { i18nAttr, i18nKey } = element.dataset;
    if (selectedTranslations[i18nKey]) {
      element.setAttribute(i18nAttr, selectedTranslations[i18nKey]);
    }
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === selectedLanguage;
    button.classList.toggle('active', active);
  });

  localStorage.setItem('preferredLanguage', selectedLanguage);
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => applyTranslations(button.dataset.lang));
});

const initialLanguage = localStorage.getItem('preferredLanguage') || 'pt';
applyTranslations(initialLanguage);
